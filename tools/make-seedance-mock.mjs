#!/usr/bin/env node
// Development tool: regenerate src/host/seedance/mock-video.ts from a local ffmpeg.
// Not used by tests. Child processes run without a shell and with array arguments.
import { spawn } from "node:child_process";
import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repository = fileURLToPath(new URL("../", import.meta.url));
const target = path.join(repository, "src", "host", "seedance", "mock-video.ts");
const limit = 64 * 1024;

function run(file, args) {
  return new Promise((resolve) => {
    let stderr = "";
    const child = spawn(file, args, { shell: false, windowsHide: true, stdio: ["ignore", "ignore", "pipe"] });
    child.stderr.on("data", (bytes) => { if (stderr.length < 65536) stderr += bytes.toString("utf8"); });
    child.once("error", () => resolve({ code: null, stderr }));
    child.once("close", (code) => resolve({ code, stderr }));
  });
}

async function findFfmpeg() {
  for (const candidate of [process.env.FFMPEG_PATH, "ffmpeg"]) {
    if (candidate && (await run(candidate, ["-version"])).code === 0) return candidate;
  }
  return null;
}

const ffmpeg = await findFfmpeg();
if (!ffmpeg) {
  console.error("ffmpeg が見つかりません。PATH に ffmpeg を置くか、FFMPEG_PATH に実行ファイルのパスを指定してください。");
  process.exit(2);
}
const directory = await fs.mkdtemp(path.join(os.tmpdir(), "smm-seedance-mock-"));
try {
  const output = path.join(directory, "mock.mp4");
  const result = await run(ffmpeg, ["-nostdin", "-hide_banner", "-loglevel", "error", "-y",
    "-f", "lavfi", "-i", "testsrc2=size=320x180:rate=12:duration=5",
    "-c:v", "libx264", "-preset", "veryslow", "-crf", "38", "-pix_fmt", "yuv420p",
    "-profile:v", "high", "-g", "60", "-an", "-movflags", "+faststart",
    "-metadata", "comment=Shin-MotionMaker Seedance mock", "-map_metadata", "-1",
    "-fflags", "+bitexact", "-flags:v", "+bitexact", output]);
  if (result.code !== 0) {
    console.error(`ffmpeg が失敗しました（終了コード ${result.code}）。\n${result.stderr}`);
    process.exit(3);
  }
  const bytes = await fs.readFile(output);
  if (bytes.length > limit) {
    console.error(`生成したモック MP4 が ${bytes.length} バイトで、上限 ${limit} バイトを超えています。`);
    process.exit(3);
  }
  const base64 = bytes.toString("base64");
  const lines = base64.match(/.{1,120}/g) ?? [];
  const body = [
    "// Generated by tools/make-seedance-mock.mjs. Do not edit by hand.",
    "// H.264 yuv420p, 320x180, 12 fps, 5 seconds, faststart. Used only by the DRY_RUN mock transport.",
    `export const MOCK_VIDEO_BYTES = ${bytes.length};`,
    "export const MOCK_VIDEO_BASE64 =",
    lines.map((line) => `  "${line}"`).join(" +\n") + ";",
    "export function mockVideo(): Uint8Array {",
    "  return new Uint8Array(Buffer.from(MOCK_VIDEO_BASE64, \"base64\"));",
    "}",
    "",
  ].join("\n");
  await fs.writeFile(target, body);
  console.log(`${path.relative(repository, target).split(path.sep).join("/")} を書き出しました（${bytes.length} バイト）。`);
} finally {
  await fs.rm(directory, { recursive: true, force: true });
}
